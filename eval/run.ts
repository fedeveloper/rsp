// Applies every labelled mutation to each corpus, runs all rules on the
// resulting diff and writes one results file per corpus. Exits 1 if any rule
// misses a risky mutation or reports on a mutation it was not expected to.
//
// The corpus in this repository is the sample Python project in eval/project
// (eval/RESULTS.md). RSP_EVAL_EXTRA adds corpora kept outside the repository,
// such as real applications whose code should not be copied here: a list of
// files separated by the path delimiter, each with a default export that
// receives the mutation helpers and returns { repo, commit, describe,
// mutations }. Each file's results are written next to it as
// RESULTS-<name>.md, and its repository is cloned at run time.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, delimiter, dirname, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { check } from "../src/index.js";
import { ALL_RULES } from "../src/rules/index.js";
import type { Finding } from "../src/types.js";
import { VERSION } from "../src/version.js";
import { makeRepoFromTrees } from "../test/helpers.js";
import * as helpers from "./mutations.js";
import { type Files, MUTATIONS, type Mutation } from "./mutations.js";

interface Corpus {
  /** What the mutations are applied to, as a sentence fragment for the report. */
  describe: string;
  source: string;
  files: Files;
  mutations: Mutation[];
  results: string;
}

interface Outcome {
  mutation: Mutation;
  findings: Finding[];
  reported: string[];
  missed: string[];
  unexpected: string[];
}

/** Files of a repository at a commit, cloned once into eval/.cache. */
function readRepo(url: string, commit: string): Files {
  const dir = join(import.meta.dirname, ".cache", url.split("/").pop()!);
  const git = (args: string[]) => execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", maxBuffer: 1 << 26 });
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    execFileSync("git", ["clone", "--quiet", "--no-checkout", url, dir]);
  }
  try {
    git(["cat-file", "-e", `${commit}^{commit}`]);
  } catch {
    git(["fetch", "--quiet", "origin", commit]);
  }
  const files: Files = new Map();
  for (const path of git(["ls-tree", "-r", "--name-only", commit]).split("\n").filter(Boolean)) {
    files.set(path, git(["show", `${commit}:${path}`]));
  }
  return files;
}

function readTree(dir: string, root = dir, files: Files = new Map()): Files {
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) readTree(path, root, files);
    else files.set(relative(root, path), readFileSync(path, "utf8"));
  }
  return files;
}

function evaluate(project: Files, mutation: Mutation): Outcome {
  const head = new Map(project);
  mutation.apply(head);
  const repo = makeRepoFromTrees(project, head);
  try {
    const findings = check({ repoDir: repo.dir, base: repo.base, head: repo.head }).findings;
    const reported = [...new Set(findings.map((f) => f.ruleId))].sort();
    return {
      mutation,
      findings,
      reported,
      missed: mutation.expect.filter((r) => !reported.includes(r)),
      unexpected: reported.filter((r) => !mutation.expect.includes(r)),
    };
  } finally {
    repo.cleanup();
  }
}

function pct(n: number, d: number): string {
  return d === 0 ? "n/a" : `${Math.round((100 * n) / d)}%`;
}

function render(corpus: Corpus, outcomes: Outcome[]): string {
  const risky = outcomes.filter((o) => o.mutation.kind === "risky").length;
  const out = [
    "# Evaluation results",
    "",
    `Generated by \`npm run eval\` with rsp ${VERSION}. Do not edit by hand.`,
    "",
    `The corpus is ${corpus.describe} and ${outcomes.length} labelled mutations of it ` +
      `(\`${corpus.source}\`): ${risky} risky changes, each naming the rules that must report it, and ` +
      `${outcomes.length - risky} benign changes that must produce no findings. Each mutation becomes a ` +
      "two-commit git repository and every rule runs on its diff.",
    "",
    "## By rule",
    "",
    "Counted per mutation and rule. A true positive is an expected rule that reported; a false negative an " +
      "expected rule that did not; a false positive a rule that reported on a mutation it was not expected for.",
    "",
    "| Rule | True positives | False negatives | False positives | Precision | Recall |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const rule of ALL_RULES.map((r) => r.id).sort()) {
    const tp = outcomes.filter((o) => o.mutation.expect.includes(rule) && o.reported.includes(rule)).length;
    const fn = outcomes.filter((o) => o.missed.includes(rule)).length;
    const fp = outcomes.filter((o) => o.unexpected.includes(rule)).length;
    out.push(`| \`${rule}\` | ${tp} | ${fn} | ${fp} | ${pct(tp, tp + fp)} | ${pct(tp, tp + fn)} |`);
  }

  out.push("", "## By mutation", "", "| Mutation | Kind | Change | Expected | Reported | Result |", "| --- | --- | --- | --- | --- | --- |");
  for (const o of outcomes) {
    const ok = o.missed.length === 0 && o.unexpected.length === 0;
    const result = ok
      ? "pass"
      : ["FAIL", ...o.missed.map((r) => `missed ${r}`), ...o.unexpected.map((r) => `unexpected ${r}`)].join(", ");
    const list = (rules: string[]) => (rules.length ? rules.map((r) => `\`${r}\``).join(", ") : "none");
    out.push(
      `| \`${o.mutation.id}\` | ${o.mutation.kind} | ${o.mutation.description} | ${list(o.mutation.expect)} | ${list(o.reported)} | ${result} |`,
    );
  }

  out.push("", "## Findings reported", "");
  for (const o of outcomes.filter((o) => o.findings.length > 0)) {
    out.push(`**${o.mutation.id}**`, "");
    for (const f of o.findings) {
      const loc = f.locations[0];
      const where = loc ? `${loc.path}${loc.line ? `:${loc.line}` : ""}` : "";
      out.push(`- \`${f.ruleId}\` \`${where}\`: ${f.message.replace(/\|/g, "\\|")}`);
    }
    out.push("");
  }
  return out.join("\n");
}

const corpora: Corpus[] = [
  {
    describe: "the sample Python project in `eval/project`",
    source: "eval/mutations.ts",
    files: readTree(join(import.meta.dirname, "project")),
    mutations: MUTATIONS,
    results: join(import.meta.dirname, "RESULTS.md"),
  },
];
for (const path of (process.env.RSP_EVAL_EXTRA ?? "").split(delimiter).filter(Boolean)) {
  const file = resolve(path);
  const extra = (await import(pathToFileURL(file).href)).default(helpers) as {
    repo: string;
    commit: string;
    describe: string;
    mutations: Mutation[];
  };
  corpora.push({
    describe: `${extra.describe} at commit \`${extra.commit.slice(0, 12)}\`, cloned at run time`,
    source: basename(file),
    files: readRepo(extra.repo, extra.commit),
    mutations: extra.mutations,
    results: join(dirname(file), `RESULTS-${basename(file).replace(/^mutations-|\.[jt]s$/g, "")}.md`),
  });
}

let failures = 0;
for (const corpus of corpora) {
  const outcomes = corpus.mutations.map((m) => evaluate(corpus.files, m));
  writeFileSync(corpus.results, render(corpus, outcomes));
  const failed = outcomes.filter((o) => o.missed.length > 0 || o.unexpected.length > 0);
  for (const o of failed) {
    process.stderr.write(`FAIL ${o.mutation.id}: missed [${o.missed}] unexpected [${o.unexpected}]\n`);
  }
  failures += failed.length;
  process.stdout.write(
    `${outcomes.length - failed.length}/${outcomes.length} mutations as expected; wrote ${relative(process.cwd(), corpus.results)}\n`,
  );
}
process.exitCode = failures > 0 ? 1 : 0;
