// Applies every labelled mutation to eval/project, runs all rules on the
// resulting diff and writes eval/RESULTS.md. Exits 1 if any rule misses a risky
// mutation or reports on a mutation it was not expected to.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { check } from "../src/index.js";
import { ALL_RULES } from "../src/rules/index.js";
import type { Finding } from "../src/types.js";
import { VERSION } from "../src/version.js";
import { makeRepoFromTrees } from "../test/helpers.js";
import { type Files, MUTATIONS, type Mutation } from "./mutations.js";

const PROJECT = join(import.meta.dirname, "project");
const RESULTS = join(import.meta.dirname, "RESULTS.md");

interface Outcome {
  mutation: Mutation;
  findings: Finding[];
  reported: string[];
  missed: string[];
  unexpected: string[];
}

function readTree(dir: string, root = dir, files: Files = new Map()): Files {
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) readTree(path, root, files);
    else files.set(relative(root, path), readFileSync(path, "utf8"));
  }
  return files;
}

function evaluate(project: Files, mutation: Mutation): Outcome {
  const head = new Map(project);
  mutation.apply(head);
  const repo = makeRepoFromTrees(project, head);
  try {
    const findings = check({ repoDir: repo.dir, base: repo.base, head: repo.head }).findings;
    const reported = [...new Set(findings.map((f) => f.ruleId))].sort();
    return {
      mutation,
      findings,
      reported,
      missed: mutation.expect.filter((r) => !reported.includes(r)),
      unexpected: reported.filter((r) => !mutation.expect.includes(r)),
    };
  } finally {
    repo.cleanup();
  }
}

function pct(n: number, d: number): string {
  return d === 0 ? "n/a" : `${Math.round((100 * n) / d)}%`;
}

function render(outcomes: Outcome[]): string {
  const risky = outcomes.filter((o) => o.mutation.kind === "risky").length;
  const out = [
    "# Evaluation results",
    "",
    `Generated by \`npm run eval\` with rsp ${VERSION}. Do not edit by hand.`,
    "",
    `The corpus is the sample project in \`eval/project\` and ${outcomes.length} labelled mutations of it ` +
      `(\`eval/mutations.ts\`): ${risky} risky changes, each naming the rules that must report it, and ` +
      `${outcomes.length - risky} benign changes that must produce no findings. Each mutation becomes a ` +
      "two-commit git repository and every rule runs on its diff.",
    "",
    "## By rule",
    "",
    "Counted per mutation and rule. A true positive is an expected rule that reported; a false negative an " +
      "expected rule that did not; a false positive a rule that reported on a mutation it was not expected for.",
    "",
    "| Rule | True positives | False negatives | False positives | Precision | Recall |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const rule of ALL_RULES.map((r) => r.id).sort()) {
    const tp = outcomes.filter((o) => o.mutation.expect.includes(rule) && o.reported.includes(rule)).length;
    const fn = outcomes.filter((o) => o.missed.includes(rule)).length;
    const fp = outcomes.filter((o) => o.unexpected.includes(rule)).length;
    out.push(`| \`${rule}\` | ${tp} | ${fn} | ${fp} | ${pct(tp, tp + fp)} | ${pct(tp, tp + fn)} |`);
  }

  out.push("", "## By mutation", "", "| Mutation | Kind | Change | Expected | Reported | Result |", "| --- | --- | --- | --- | --- | --- |");
  for (const o of outcomes) {
    const ok = o.missed.length === 0 && o.unexpected.length === 0;
    const result = ok
      ? "pass"
      : ["FAIL", ...o.missed.map((r) => `missed ${r}`), ...o.unexpected.map((r) => `unexpected ${r}`)].join(", ");
    const list = (rules: string[]) => (rules.length ? rules.map((r) => `\`${r}\``).join(", ") : "none");
    out.push(
      `| \`${o.mutation.id}\` | ${o.mutation.kind} | ${o.mutation.description} | ${list(o.mutation.expect)} | ${list(o.reported)} | ${result} |`,
    );
  }

  out.push("", "## Findings reported", "");
  for (const o of outcomes.filter((o) => o.findings.length > 0)) {
    out.push(`**${o.mutation.id}**`, "");
    for (const f of o.findings) {
      const loc = f.locations[0];
      const where = loc ? `${loc.path}${loc.line ? `:${loc.line}` : ""}` : "";
      out.push(`- \`${f.ruleId}\` \`${where}\`: ${f.message.replace(/\|/g, "\\|")}`);
    }
    out.push("");
  }
  return out.join("\n");
}

const project = readTree(PROJECT);
const outcomes = MUTATIONS.map((m) => evaluate(project, m));
writeFileSync(RESULTS, render(outcomes));

const failed = outcomes.filter((o) => o.missed.length > 0 || o.unexpected.length > 0);
for (const o of failed) {
  process.stderr.write(`FAIL ${o.mutation.id}: missed [${o.missed}] unexpected [${o.unexpected}]\n`);
}
process.stdout.write(`${outcomes.length - failed.length}/${outcomes.length} mutations as expected; wrote ${relative(process.cwd(), RESULTS)}\n`);
process.exitCode = failed.length > 0 ? 1 : 0;
